-- All writers, including the administrative API, serialize conflicts per professional.
CREATE FUNCTION prevent_booking_overlap() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE current_start timestamptz; current_end timestamptz; current_status text;
BEGIN
 PERFORM pg_advisory_xact_lock(70421, NEW.employee_id);
 SELECT schedule_started_at,schedule_ended_at,status INTO current_start,current_end,current_status FROM salon_schedules WHERE id=NEW.schedule_id;
 IF current_status <> 'cancelled' AND EXISTS(
  SELECT 1 FROM salon_schedule_treatments t JOIN salon_schedules s ON s.id=t.schedule_id
  WHERE t.employee_id=NEW.employee_id AND s.id<>NEW.schedule_id AND s.status<>'cancelled'
    AND s.schedule_started_at<current_end AND s.schedule_ended_at>current_start
 ) THEN RAISE EXCEPTION 'Professional is unavailable' USING ERRCODE='23P01'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER prevent_booking_overlap BEFORE INSERT OR UPDATE ON salon_schedule_treatments FOR EACH ROW EXECUTE FUNCTION prevent_booking_overlap();
-- Rescheduling and reactivation cannot bypass the same interval protection.
CREATE FUNCTION prevent_schedule_overlap() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE professional integer;
BEGIN
 IF NEW.status='cancelled' OR (OLD.status<>'cancelled' AND NEW.schedule_started_at=OLD.schedule_started_at AND NEW.schedule_ended_at=OLD.schedule_ended_at) THEN RETURN NEW; END IF;
 FOR professional IN SELECT employee_id FROM salon_schedule_treatments WHERE schedule_id=NEW.id ORDER BY employee_id LOOP
  PERFORM pg_advisory_xact_lock(70421, professional);
  IF NEW.status<>'cancelled' AND EXISTS(SELECT 1 FROM salon_schedule_treatments t JOIN salon_schedules s ON s.id=t.schedule_id WHERE t.employee_id=professional AND s.id<>NEW.id AND s.status<>'cancelled' AND s.schedule_started_at<NEW.schedule_ended_at AND s.schedule_ended_at>NEW.schedule_started_at)
  THEN RAISE EXCEPTION 'Professional is unavailable' USING ERRCODE='23P01'; END IF;
 END LOOP;
 RETURN NEW;
END $$;
CREATE TRIGGER prevent_schedule_overlap BEFORE UPDATE OF schedule_started_at,schedule_ended_at,status ON salon_schedules FOR EACH ROW EXECUTE FUNCTION prevent_schedule_overlap();
