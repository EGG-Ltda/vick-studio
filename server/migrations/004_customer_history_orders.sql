CREATE FUNCTION snapshot_treatment_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN SELECT name INTO NEW.treatment_name FROM salon_treatments WHERE id=NEW.treatment_id;
 ELSE NEW.treatment_name=OLD.treatment_name; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER snapshot_treatment_name BEFORE INSERT OR UPDATE ON salon_schedule_treatments FOR EACH ROW EXECUTE FUNCTION snapshot_treatment_name();
