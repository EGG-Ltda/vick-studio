CREATE TABLE access_classes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL CHECK(length(trim(name)) BETWEEN 2 AND 80),description text NOT NULL DEFAULT '' CHECK(length(description)<=1000),
 level text NOT NULL CHECK(level IN ('administrative','operational')),
 data_scope text NOT NULL CHECK(data_scope IN ('own','salon')),
 builtin_role text UNIQUE REFERENCES access_profiles(role),active boolean NOT NULL DEFAULT true,
 admin_manageable boolean NOT NULL DEFAULT false,version integer NOT NULL DEFAULT 1,
 created_by integer REFERENCES app_users(id),updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX access_class_name ON access_classes(lower(trim(name)));
INSERT INTO access_classes(name,level,data_scope,builtin_role,admin_manageable) VALUES('Admin','administrative','salon','ADMIN',false),('Operacional','operational','own','OPERATIONAL',true);
CREATE TABLE class_permissions(class_id integer NOT NULL REFERENCES access_classes(id),permission_key text NOT NULL,allowed boolean NOT NULL DEFAULT false,delegatable boolean NOT NULL DEFAULT false,PRIMARY KEY(class_id,permission_key));
ALTER TABLE app_users ADD COLUMN access_class_id integer REFERENCES access_classes(id);
UPDATE app_users u SET access_class_id=c.id FROM access_classes c WHERE c.builtin_role=u.role;
CREATE INDEX users_access_class ON app_users(access_class_id);
CREATE FUNCTION sync_access_class() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE policy access_classes%ROWTYPE;
BEGIN
 IF NEW.role='MASTER' THEN NEW.access_class_id=NULL;RETURN NEW;END IF;
 IF TG_OP='UPDATE' AND NEW.role<>OLD.role AND NEW.access_class_id IS NOT DISTINCT FROM OLD.access_class_id THEN NEW.access_class_id=NULL;END IF;
 IF NEW.access_class_id IS NULL THEN SELECT id INTO NEW.access_class_id FROM access_classes WHERE builtin_role=NEW.role; END IF;
 SELECT * INTO policy FROM access_classes WHERE id=NEW.access_class_id;
 IF NOT FOUND OR NOT policy.active THEN RAISE EXCEPTION 'Active access class required' USING ERRCODE='23514'; END IF;
 NEW.role=CASE WHEN policy.level='administrative' THEN 'ADMIN' ELSE 'OPERATIONAL' END;
 NEW.is_admin=NEW.role='ADMIN';RETURN NEW;
END $$;
-- Runs after the legacy role/is_admin synchronizer.
CREATE TRIGGER zz_sync_access_class BEFORE INSERT OR UPDATE OF role,is_admin,access_class_id ON app_users FOR EACH ROW EXECUTE FUNCTION sync_access_class();
CREATE FUNCTION protect_access_class_status() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF (NOT NEW.active OR NEW.level<>OLD.level) AND EXISTS(SELECT 1 FROM app_users WHERE access_class_id=OLD.id) THEN RAISE EXCEPTION 'Reassign linked users before deactivating or changing class level' USING ERRCODE='23514';END IF;
 IF OLD.builtin_role IS NOT NULL AND (NOT NEW.active OR NEW.builtin_role IS DISTINCT FROM OLD.builtin_role OR NEW.level<>OLD.level) THEN RAISE EXCEPTION 'Built-in access class is protected' USING ERRCODE='23514';END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER protect_access_class_status BEFORE UPDATE ON access_classes FOR EACH ROW EXECUTE FUNCTION protect_access_class_status();
INSERT INTO profile_permissions(role,permission_key,allowed,delegatable) SELECT role,'classes.manage',false,false FROM access_profiles;
CREATE VIEW effective_class_permissions AS
 SELECT c.id AS class_id,p.permission_key,p.allowed,p.delegatable FROM access_classes c JOIN profile_permissions p ON p.role=c.builtin_role
 UNION ALL SELECT c.id,p.permission_key,p.allowed,p.delegatable FROM access_classes c JOIN class_permissions p ON p.class_id=c.id WHERE c.builtin_role IS NULL;
