BEGIN;

-- Repair the missing primary key without deleting existing records.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'salon_treatments'::regclass AND contype = 'p') THEN
    ALTER TABLE salon_treatments ADD PRIMARY KEY (id);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS finance_treatment_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_item_id INTEGER NOT NULL UNIQUE REFERENCES salon_schedule_treatments(id),
  schedule_id INTEGER NOT NULL REFERENCES salon_schedules(id),
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  treatment_id INTEGER NOT NULL REFERENCES salon_treatments(id),
  employee_name TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  treatment_name TEXT NOT NULL,
  performed_on DATE NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
  unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents BETWEEN 0 AND 1000000000),
  gross_cents BIGINT GENERATED ALWAYS AS (quantity::bigint * unit_price_cents) STORED,
  discount_cents BIGINT NOT NULL DEFAULT 0 CHECK (discount_cents >= 0 AND discount_cents <= quantity::bigint * unit_price_cents),
  final_cents BIGINT GENERATED ALWAYS AS (quantity::bigint * unit_price_cents - discount_cents) STORED,
  actual_started_at TIMESTAMPTZ,
  actual_ended_at TIMESTAMPTZ,
  status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed','cancelled','reversed')),
  reversal_reason TEXT,
  reversed_at TIMESTAMPTZ,
  reversed_by INTEGER REFERENCES app_users(id),
  created_by INTEGER NOT NULL REFERENCES app_users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((actual_started_at IS NULL AND actual_ended_at IS NULL) OR
    (actual_started_at IS NOT NULL AND actual_ended_at IS NOT NULL AND actual_ended_at > actual_started_at))
);
CREATE INDEX IF NOT EXISTS finance_treatments_period ON finance_treatment_records(performed_on, employee_id, treatment_id) WHERE status = 'completed';

CREATE TABLE IF NOT EXISTS salon_products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  price_cents BIGINT NOT NULL CHECK (price_cents BETWEEN 0 AND 1000000000),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS salon_product_sales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  customer_id INTEGER REFERENCES customers(id),
  sold_on DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'completed' CHECK (status IN ('completed','cancelled','reversed')),
  reversal_reason TEXT,
  reversed_at TIMESTAMPTZ,
  reversed_by INTEGER REFERENCES app_users(id),
  created_by INTEGER NOT NULL REFERENCES app_users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS salon_product_sale_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id INTEGER NOT NULL REFERENCES salon_product_sales(id),
  product_id INTEGER NOT NULL REFERENCES salon_products(id),
  product_name TEXT NOT NULL,
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
  unit_price_cents BIGINT NOT NULL CHECK (unit_price_cents BETWEEN 0 AND 1000000000),
  gross_cents BIGINT GENERATED ALWAYS AS (quantity::bigint * unit_price_cents) STORED,
  discount_cents BIGINT NOT NULL DEFAULT 0 CHECK (discount_cents >= 0 AND discount_cents <= quantity::bigint * unit_price_cents),
  final_cents BIGINT GENERATED ALWAYS AS (quantity::bigint * unit_price_cents - discount_cents) STORED,
  UNIQUE(sale_id, product_id)
);
CREATE INDEX IF NOT EXISTS finance_sales_period ON salon_product_sales(sold_on, employee_id) WHERE status = 'completed';

INSERT INTO app_permissions(name,description,created_at)
SELECT name, description, NOW() FROM (VALUES
  ('finance.read', 'View financial reports'),
  ('finance.write', 'Record completed treatments, product sales and reversals'),
  ('finance.export', 'Export financial reports')
) AS permissions(name,description)
WHERE NOT EXISTS (SELECT 1 FROM app_permissions p WHERE p.name = permissions.name);
COMMIT;
