const { test } = require('node:test')
const assert = require('node:assert/strict')
const { randomBytes } = require('node:crypto')
const { spawn, execFileSync } = require('node:child_process')
const path = require('node:path')
const net = require('node:net')
const { setTimeout: delay } = require('node:timers/promises')
const { Client } = require('pg')
const bcrypt = require('bcryptjs')

const serverRoot = path.resolve(__dirname, '..')
const randomPassword = () => randomBytes(15).toString('base64url')

test(
  'senha temporária, autorização, bloqueio e troca de uso único',
  { timeout: 90000 },
  async (t) => {
    assert.ok(
      process.env.TEST_DATABASE_CONNECTION_STRING,
      'Defina TEST_DATABASE_CONNECTION_STRING para um PostgreSQL local com permissão de criar bancos de teste.',
    )
    const admin = new Client({
      connectionString: process.env.TEST_DATABASE_CONNECTION_STRING,
    })
    const databaseName = `password_reset_test_${randomBytes(8).toString('hex')}`
    const databaseUrl = new URL(process.env.TEST_DATABASE_CONNECTION_STRING)
    databaseUrl.pathname = `/${databaseName}`
    const connectionString = databaseUrl.toString()
    let databaseCreated = false
    let database
    let server
    const masterPassword = randomPassword()
    const adminPassword = randomPassword()
    const originalPassword = randomPassword()
    const jwtSecret = randomPassword() + randomPassword()
    let base

    async function request(method, route, cookie = '', body) {
      const response = await fetch(`${base}/api${route}`, {
        method,
        headers: {
          Cookie: cookie,
          ...(body === undefined ? {} : { 'Content-Type': 'application/json' }),
        },
        body: body === undefined ? undefined : JSON.stringify(body),
      })
      return {
        status: response.status,
        body: await response.json(),
        cookie: response.headers
          .getSetCookie()
          .map((value) => value.split(';')[0])
          .join('; '),
      }
    }
    const login = (name, password) =>
      request('POST', '/auth/signin', '', { login: name, password })
    const reset = (id, cookie, password) =>
      request('PUT', `/users/${id}/temporary-password`, cookie, {
        password,
        confirmPassword: password,
      })
    const change = (cookie, newPassword) =>
      request('POST', '/auth/change-password', cookie, {
        newPassword,
        confirmPassword: newPassword,
      })

    await admin.connect()
    try {
      await admin.query(`CREATE DATABASE "${databaseName}"`)
      databaseCreated = true
      database = new Client({ connectionString })
      await database.connect()
      // Simulate the schema and accounts that existed before this feature.
      await database.query(`CREATE TABLE app_users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      login VARCHAR(255) NOT NULL UNIQUE, email VARCHAR(255) NOT NULL,
      hash_password CHAR(60) NOT NULL, is_active BOOLEAN NOT NULL,
      created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP, removed_at TIMESTAMP
    )`)
      for (const [name, password, active] of [
        ['master', masterPassword, true],
        ['admin', adminPassword, true],
        ['employee', originalPassword, true],
        ['other-admin', randomPassword(), true],
        ['disabled', randomPassword(), false],
      ]) {
        await database.query(
          'INSERT INTO app_users (login, email, hash_password, is_active, created_at) VALUES ($1, $2, $3, $4, NOW())',
          [
            name,
            `${name}@example.test`,
            await bcrypt.hash(password, 10),
            active,
          ],
        )
      }

      await database.query(
        require('node:fs').readFileSync(
          path.join(serverRoot, '../db/init.sql'),
          'utf8',
        ),
      )
      const migrationEnv = {
        ...process.env,
        DATABASE_CONNECTION_STRING: connectionString,
      }
      execFileSync(process.execPath, ['scripts/migrate.cjs'], {
        cwd: serverRoot,
        env: migrationEnv,
        stdio: 'pipe',
      })
      execFileSync(process.execPath, ['scripts/migrate.cjs'], {
        cwd: serverRoot,
        env: migrationEnv,
        stdio: 'pipe',
      })
      await database.query(
        'UPDATE app_users SET is_admin = true WHERE id IN (2, 4)',
      )
      const listener = net.createServer()
      await new Promise((resolve) => listener.listen(0, '127.0.0.1', resolve))
      const port = listener.address().port
      await new Promise((resolve) => listener.close(resolve))
      base = `http://127.0.0.1:${port}`
      let serverOutput = ''
      server = spawn(process.execPath, ['dist/app.js'], {
        cwd: serverRoot,
        windowsHide: true,
        env: {
          ...process.env,
          DATABASE_CONNECTION_STRING: connectionString,
          PORT: String(port),
          NODE_ENV: 'test',
          MASTER_USER_ID: '1',
          JWT_TOKEN_SECRET: jwtSecret,
          JWT_TOKEN_ISSUER: 'password-tests',
          JWT_TOKEN_AUDIENCE: 'password-tests',
          JWT_TOKEN_ACCESS_EXP: '3600',
          JWT_TOKEN_REFRESH_EXP: '604800',
          JWT_TOKEN_ACCESS_TOPIC: 'access_token',
          JWT_TOKEN_REFRESH_TOPIC: 'refresh_token',
        },
        stdio: ['ignore', 'pipe', 'pipe'],
      })
      server.stdout.on('data', (data) => {
        serverOutput += data.toString()
      })
      server.stderr.on('data', (data) => {
        serverOutput += data.toString()
      })
      let ready = false
      for (let attempt = 0; attempt < 100; attempt++) {
        try {
          ready = (await fetch(`${base}/api/auth/session`)).status === 401
        } catch {
          /* Wait for the test server. */
        }
        if (ready) break
        if (server.exitCode !== null) break
        await delay(100)
      }
      assert.ok(ready, `Servidor de teste não iniciou. ${serverOutput}`)
      const master = await login('master', masterPassword)
      const administrator = await login('admin', adminPassword)
      const employee = await login('employee', originalPassword)
      const temporaryPassword = randomPassword()

      await t.test(
        'migração repetível preserva credenciais e sessões antigas válidas',
        async () => {
          assert.equal(master.status, 200)
          assert.equal(master.body.data.mustChangePassword, false)
          assert.equal(master.body.data.canManagePasswords, true)
          assert.equal(employee.status, 200)
          assert.equal(employee.body.data.canManagePasswords, false)
          assert.equal('hashPassword' in employee.body.data, false)
          assert.equal('passwordVersion' in employee.body.data, false)
          const rows = await database.query(
            'SELECT must_change_password, password_version FROM app_users WHERE id = 3',
          )
          assert.deepEqual(rows.rows[0], {
            must_change_password: false,
            password_version: 0,
          })
          const access = employee.cookie
            .split('; ')
            .find((value) => value.startsWith('accessToken='))
            .slice('accessToken='.length)
          const decoded = require('jsonwebtoken').decode(access)
          assert.equal(decoded['vick:passwordVersion'], 0)
          delete decoded['vick:passwordVersion']
          const legacyToken = require('jsonwebtoken').sign(decoded, jwtSecret)
          assert.equal(
            (
              await request(
                'GET',
                '/auth/session',
                `accessToken=${legacyToken}`,
              )
            ).status,
            200,
          )
        },
      )

      await t.test(
        'apenas ADMIN e MASTER autorizados podem redefinir senhas',
        async () => {
          assert.equal((await reset(3, '', temporaryPassword)).status, 401)
          assert.equal(
            (await reset(2, employee.cookie, temporaryPassword)).status,
            403,
          )
          assert.equal(
            (await reset(1, administrator.cookie, temporaryPassword)).status,
            403,
          )
          assert.equal(
            (await reset(4, administrator.cookie, temporaryPassword)).status,
            403,
          )
          assert.equal(
            (await reset(1, master.cookie, temporaryPassword)).status,
            409,
          )
          assert.equal(
            (await reset(5, master.cookie, temporaryPassword)).status,
            409,
          )
          assert.equal(
            (await reset(0, master.cookie, temporaryPassword)).status,
            400,
          )
          assert.equal(
            (await reset(9999, master.cookie, temporaryPassword)).status,
            404,
          )
          assert.equal(
            (await reset(3, master.cookie, originalPassword)).status,
            400,
          )
          assert.equal(
            (
              await request(
                'PUT',
                '/users/3/temporary-password',
                master.cookie,
                { password: 'short', confirmPassword: 'short' },
              )
            ).status,
            400,
          )
        },
      )

      let limitedSession
      await t.test(
        'senha temporária invalida sessões anteriores e bloqueia funcionalidades',
        async () => {
          assert.equal(
            (await reset(3, master.cookie, temporaryPassword)).status,
            200,
          )
          assert.equal(
            (await request('GET', '/users', employee.cookie)).status,
            401,
          )
          assert.equal(
            (await request('POST', '/auth/refresh', employee.cookie)).status,
            401,
          )
          assert.equal((await login('employee', originalPassword)).status, 401)
          limitedSession = await login('employee', temporaryPassword)
          assert.equal(limitedSession.status, 200)
          assert.equal(limitedSession.body.data.mustChangePassword, true)
          const blocked = await request('GET', '/users', limitedSession.cookie)
          assert.equal(blocked.status, 403)
          assert.equal(blocked.body.code, 'PASSWORD_CHANGE_REQUIRED')
          assert.equal(
            (await request('GET', '/treatments?page=0', limitedSession.cookie))
              .status,
            403,
          )
          const session = await request(
            'GET',
            '/auth/session',
            limitedSession.cookie,
          )
          assert.equal(session.status, 200)
          assert.equal(session.body.data.mustChangePassword, true)
          assert.equal((await request('POST', '/auth/signout')).status, 200)
          const refreshed = await request(
            'POST',
            '/auth/refresh',
            limitedSession.cookie,
          )
          assert.equal(refreshed.status, 200)
          assert.equal(
            (await request('GET', '/users', refreshed.cookie)).status,
            403,
          )
          assert.equal(
            (await change(limitedSession.cookie, temporaryPassword)).status,
            400,
          )
          assert.equal(
            (
              await request(
                'POST',
                '/auth/change-password',
                limitedSession.cookie,
                {
                  newPassword: randomPassword(),
                  confirmPassword: randomPassword(),
                },
              )
            ).status,
            400,
          )
        },
      )

      let personalPassword
      let fullSession
      await t.test(
        'trocas concorrentes têm um único vencedor e a senha temporária perde validade',
        async () => {
          const candidates = [randomPassword(), randomPassword()]
          const responses = await Promise.all(
            candidates.map((password) =>
              change(limitedSession.cookie, password),
            ),
          )
          assert.equal(
            responses.filter((response) => response.status === 200).length,
            1,
          )
          const winner = responses.findIndex(
            (response) => response.status === 200,
          )
          assert.ok([401, 409].includes(responses[1 - winner].status))
          personalPassword = candidates[winner]
          fullSession = responses[winner]
          assert.equal(fullSession.body.data.mustChangePassword, false)
          assert.equal(
            (await request('GET', '/users', fullSession.cookie)).status,
            200,
          )
          assert.equal(
            (await request('GET', '/auth/session', limitedSession.cookie))
              .status,
            401,
          )
          assert.equal(
            (await request('POST', '/auth/refresh', limitedSession.cookie))
              .status,
            401,
          )
          assert.equal((await login('employee', temporaryPassword)).status, 401)
          assert.equal(
            (await login('employee', candidates[1 - winner])).status,
            401,
          )
          assert.equal((await login('employee', personalPassword)).status, 200)
          assert.equal(
            (await change(fullSession.cookie, randomPassword())).status,
            409,
          )
        },
      )

      await t.test(
        'MASTER e ADMIN podem redefinir repetidamente após cada troca pessoal',
        async () => {
          for (const actor of [master, administrator]) {
            for (let cycle = 0; cycle < 3; cycle++) {
              const before = await request('GET', '/users?page=0', actor.cookie)
              assert.equal(
                before.body.data.items.find((user) => user.id === 3)
                  .canResetPassword,
                true,
              )
              const temporary = randomPassword()
              assert.equal(
                (await reset(3, actor.cookie, temporary)).status,
                200,
              )
              const limited = await login('employee', temporary)
              const changed = await change(limited.cookie, randomPassword())
              assert.equal(changed.status, 200)
              assert.equal((await login('employee', temporary)).status, 401)
              const after = await request('GET', '/users?page=0', actor.cookie)
              assert.equal(
                after.body.data.items.find((user) => user.id === 3)
                  .canResetPassword,
                true,
              )
              const regular = await request(
                'GET',
                '/users?page=0',
                changed.cookie,
              )
              assert.ok(
                regular.body.data.items.every(
                  (user) => user.canResetPassword === false,
                ),
              )
            }
          }
        },
      )

      await t.test(
        'cadastros novos exigem troca e nunca expõem hashes ou versão da senha',
        async () => {
          const created = await request('POST', '/users', master.cookie, {
            login: 'new-user',
            email: 'new-user@example.test',
            password: temporaryPassword,
            isAdmin: true,
          })
          assert.equal(created.status, 200)
          assert.equal(created.body.data.mustChangePassword, true)
          assert.equal(created.body.data.isAdmin, false)
          const users = await request('GET', '/users?page=0', master.cookie)
          for (const user of users.body.data.items) {
            assert.equal('hashPassword' in user, false)
            assert.equal('passwordVersion' in user, false)
          }
          const firstSession = await login('new-user', temporaryPassword)
          const nextTemporary = randomPassword()
          assert.equal(
            (await reset(created.body.data.id, master.cookie, nextTemporary))
              .status,
            200,
          )
          assert.equal(
            (await change(firstSession.cookie, randomPassword())).status,
            401,
          )
          assert.equal((await login('new-user', temporaryPassword)).status, 401)
          assert.equal(
            (await login('new-user', nextTemporary)).body.data
              .mustChangePassword,
            true,
          )
        },
      )

      await t.test(
        'ADMIN pode recuperar funcionário e MASTER pode recuperar ADMIN',
        async () => {
          const nextTemporary = randomPassword()
          assert.equal(
            (await reset(3, administrator.cookie, nextTemporary)).status,
            200,
          )
          assert.equal(
            (await login('employee', nextTemporary)).body.data
              .mustChangePassword,
            true,
          )
          assert.equal(
            (await reset(2, master.cookie, nextTemporary)).status,
            200,
          )
          assert.equal(
            (await reset(3, administrator.cookie, randomPassword())).status,
            401,
          )
          const limitedAdmin = await login('admin', nextTemporary)
          assert.equal(limitedAdmin.body.data.mustChangePassword, true)
          assert.equal(
            (await reset(3, limitedAdmin.cookie, randomPassword())).status,
            403,
          )
        },
      )
    } finally {
      if (server && server.exitCode === null && server.signalCode === null) {
        await new Promise((resolve) => {
          server.once('exit', resolve)
          server.kill()
        })
      }
      if (database) await database.end()
      if (databaseCreated)
        await admin.query(`DROP DATABASE "${databaseName}" WITH (FORCE)`)
      await admin.end()
    }
  },
)
